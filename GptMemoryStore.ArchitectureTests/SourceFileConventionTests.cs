using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

using NUnit.Framework;

namespace GptMemoryStore.ArchitectureTests
{
    [TestFixture]
    public sealed class SourceFileConventionTests
    {
        [TestCase("GptMemoryStore")]
        [TestCase("GptMemoryStore.ArchitectureTests")]
        [TestCase("GptMemoryStore.IntegrationTests")]
        [TestCase("GptMemoryStore.UnitTests")]
        public void GivenHandwrittenSources_WhenCheckingSyntaxAndSemantics_ThenConventionsAreSatisfied(string projectName)
        {
            CSharpCompilation compilation = ArchitectureTestSources.Compilations[projectName];
            string[] violations = [.. compilation.SyntaxTrees.SelectMany(tree =>
                SourceConventionRules.Check(tree, compilation.GetSemanticModel(tree), projectName)
                    .Concat(SpecialisedConventionRules.Check(tree, compilation.GetSemanticModel(tree))))];

            Assert.That(violations, Is.Empty, string.Join(Environment.NewLine, violations));
        }

        [TestCase("GptMemoryStore")]
        [TestCase("GptMemoryStore.ArchitectureTests")]
        [TestCase("GptMemoryStore.IntegrationTests")]
        [TestCase("GptMemoryStore.UnitTests")]
        public void GivenAProductionProject_WhenCheckingSourceFiles_ThenEachFileDefinesOneMatchingType(
            string projectName)
        {
            string projectDirectory = Path.Combine(FindRepositoryRoot(), projectName);
            Assert.That(
                File.Exists(Path.Combine(projectDirectory, $"{projectName}.csproj")),
                Is.True,
                $"The required production project {projectName} must be available.");

            string[] sourceFiles = [.. EnumerateSourceFiles(projectDirectory)
                .Where(filePath => !IsGeneratedSource(filePath, File.ReadAllText(filePath)))
                .OrderBy(filePath => filePath, StringComparer.Ordinal)];

            Assert.That(sourceFiles, Is.Not.Empty, $"{projectName} must contain handwritten C# sources.");

            string[] violations = [.. sourceFiles.SelectMany(filePath => GetConventionViolations(filePath, File.ReadAllText(filePath)))];

            Assert.That(violations, Is.Empty, string.Join(Environment.NewLine, violations));
        }

        [TestCase("Memory.cs", "class Memory {}", 0)]
        [TestCase("Memory.cs", "interface Memory {}", 0)]
        [TestCase("Memory.cs", "struct Memory {}", 0)]
        [TestCase("Memory.cs", "record Memory;", 0)]
        [TestCase("Memory.cs", "record struct Memory;", 0)]
        [TestCase("Memory.cs", "enum Memory { Stored }", 0)]
        [TestCase("Memory.cs", "delegate void Memory();", 0)]
        [TestCase("Memory.cs", "class Memory<TContent> {}", 0)]
        [TestCase("Memory.cs", "class @Memory {}", 0)]
        [TestCase("Memory.cs", "partial class Memory {}", 0)]
        [TestCase("Memory.cs", "namespace Store; class Memory {}", 0)]
        [TestCase("Memory.cs", "namespace Store { class Memory {} }", 0)]
        [TestCase("Memory.cs", "", 1)]
        [TestCase("Program.cs", "System.Console.WriteLine();", 1)]
        [TestCase("Memory.cs", "class Memory {} class Content {}", 1)]
        [TestCase("Memory.cs", "class Memory { class Content {} }", 1)]
        [TestCase("Memory.cs", "class Memory { delegate void Content(); }", 1)]
        [TestCase("Memory.cs", "partial class Memory {} partial class Memory {}", 1)]
        [TestCase("memory.cs", "class Memory {}", 1)]
        [TestCase("Content.cs", "class Memory {}", 1)]
        [TestCase("Memory.Partial.cs", "partial class Memory {}", 1)]
        public void GivenSourceText_WhenCheckingConventions_ThenExpectedViolationsAreReported(
            string filePath,
            string source,
            int expectedViolationCount)
        {
            string[] violations = [.. GetConventionViolations(filePath, source)];

            Assert.That(violations, Has.Length.EqualTo(expectedViolationCount));
            Assert.That(violations.All(violation => violation.Contains(filePath)), Is.True);
        }

        [TestCase("Memory.cs", "class Memory {}", false)]
        [TestCase("Memory.g.cs", "class Memory {}", true)]
        [TestCase("Memory.g.i.cs", "class Memory {}", true)]
        [TestCase("Memory.generated.cs", "class Memory {}", true)]
        [TestCase("Memory.designer.cs", "class Memory {}", true)]
        [TestCase("Memory.cs", "// <auto-generated/>\nclass Memory {}", true)]
        [TestCase("Memory.cs", "/* <auto-generated> */\r\nclass Memory {}", true)]
        [TestCase("Memory.cs", "class Memory { string Content = \"<auto-generated\"; }", false)]
        public void GivenASourceFile_WhenCheckingGeneratedCode_ThenOnlyGeneratedFilesAreExcluded(
            string filePath,
            string source,
            bool isGenerated)
            => Assert.That(IsGeneratedSource(filePath, source), Is.EqualTo(isGenerated));

        private static string FindRepositoryRoot()
        {
            DirectoryInfo? directory = new(TestContext.CurrentContext.TestDirectory);

            while (directory is not null)
            {
                if (File.Exists(Path.Combine(directory.FullName, "GptMemoryStore.slnx")))
                {
                    return directory.FullName;
                }

                directory = directory.Parent;
            }

            throw new DirectoryNotFoundException(
                "Source-file convention tests require the repository checkout, including GptMemoryStore.slnx.");
        }

        private static IEnumerable<string> EnumerateSourceFiles(string directory)
        {
            foreach (string filePath in Directory.EnumerateFiles(directory, "*.cs"))
            {
                yield return filePath;
            }

            foreach (string childDirectory in Directory.EnumerateDirectories(directory))
            {
                string directoryName = Path.GetFileName(childDirectory);

                if (string.Equals(directoryName, "bin", StringComparison.OrdinalIgnoreCase) ||
                    string.Equals(directoryName, "obj", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                foreach (string filePath in EnumerateSourceFiles(childDirectory))
                {
                    yield return filePath;
                }
            }
        }

        private static bool IsGeneratedSource(string filePath, string source)
        {
            string[] generatedSuffixes = [".g.cs", ".g.i.cs", ".generated.cs", ".designer.cs"];

            return generatedSuffixes.Any(suffix => filePath.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) ||
                CSharpSyntaxTree.ParseText(source).GetRoot().GetLeadingTrivia()
                    .Any(trivia => trivia.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));
        }

        private static IEnumerable<string> GetConventionViolations(string filePath, string source)
        {
            SyntaxNode root = CSharpSyntaxTree.ParseText(source).GetRoot();
            string[] typeNames = [.. root.DescendantNodes()
                .Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax)
                .Select(node => node switch
                {
                    BaseTypeDeclarationSyntax declaration => declaration.Identifier.ValueText,
                    DelegateDeclarationSyntax declaration => declaration.Identifier.ValueText,
                    _ => throw new InvalidOperationException("An unexpected type declaration was selected.")
                })];

            if (typeNames.Length != 1)
            {
                yield return $"{filePath}: Expected exactly one declared type, including nested types; found {typeNames.Length}.";
                yield break;
            }

            if (!string.Equals(Path.GetFileNameWithoutExtension(filePath), typeNames[0], StringComparison.Ordinal))
            {
                yield return $"{filePath}: The filename must match the declared type exactly: {typeNames[0]}.cs.";
            }
        }
    }
}