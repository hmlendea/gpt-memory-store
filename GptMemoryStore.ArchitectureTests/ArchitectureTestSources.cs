using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

using NUnit.Framework;

namespace GptMemoryStore.ArchitectureTests
{
    internal static class ArchitectureTestSources
    {
        internal static readonly string[] ProjectNames =
        [
            "GptMemoryStore",
            "GptMemoryStore.ArchitectureTests",
            "GptMemoryStore.IntegrationTests",
            "GptMemoryStore.UnitTests"
        ];

        internal static readonly string Root = FindRepositoryRoot();

        internal static readonly IReadOnlyDictionary<string, CSharpCompilation> Compilations = BuildCompilations()
            .ToDictionary(pair => pair.Key, pair => pair.Value);

        internal static IEnumerable<SyntaxTree> GetTrees(string projectName)
            => Compilations[projectName].SyntaxTrees;

        internal static string GetRole(string filePath)
        {
            string relativePath = Path.GetRelativePath(Root, filePath).Replace(Path.DirectorySeparatorChar, '/');

            if (!relativePath.StartsWith("GptMemoryStore/", StringComparison.Ordinal))
            {
                return "Test";
            }

            string[] segments = relativePath.Split('/');

            if (segments.Length < 3)
            {
                return "Composition";
            }

            return segments[1];
        }

        internal static bool IsGenerated(string filePath, string source)
        {
            string[] suffixes = [".g.cs", ".g.i.cs", ".generated.cs", ".designer.cs"];

            return suffixes.Any(suffix => filePath.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) ||
                CSharpSyntaxTree.ParseText(source).GetRoot().GetLeadingTrivia()
                    .Any(trivia => trivia.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));
        }

        internal static IEnumerable<string> EnumerateFiles(string directory)
        {
            foreach (string filePath in Directory.EnumerateFiles(directory, "*.cs"))
            {
                if (!IsGenerated(filePath, File.ReadAllText(filePath)))
                {
                    yield return filePath;
                }
            }

            foreach (string childDirectory in Directory.EnumerateDirectories(directory))
            {
                string name = Path.GetFileName(childDirectory);

                if (!string.Equals(name, "bin", StringComparison.OrdinalIgnoreCase) &&
                    !string.Equals(name, "obj", StringComparison.OrdinalIgnoreCase))
                {
                    foreach (string filePath in EnumerateFiles(childDirectory))
                    {
                        yield return filePath;
                    }
                }
            }
        }

        private static string FindRepositoryRoot()
        {
            DirectoryInfo? directory = new(TestContext.CurrentContext.TestDirectory);

            while (directory is not null)
            {
                if (File.Exists(Path.Combine(directory.FullName, "GptMemoryStore.slnx")))
                {
                    return directory.FullName;
                }

                directory = directory.Parent;
            }

            throw new DirectoryNotFoundException("Architecture tests require a checkout containing GptMemoryStore.slnx.");
        }

        private static IEnumerable<KeyValuePair<string, CSharpCompilation>> BuildCompilations()
        {
            Dictionary<string, CSharpCompilation> compilations = [];
            string runtimeAssemblies = string.Empty;

            if (AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") is string paths)
            {
                runtimeAssemblies = paths;
            }
            IEnumerable<string> assemblyPaths = runtimeAssemblies.Split(Path.PathSeparator)
                .Where(File.Exists)
                .Concat(ProjectNames.SelectMany(projectName =>
                    Directory.EnumerateFiles(Path.Combine(Root, projectName, "bin"), "*.dll", SearchOption.AllDirectories)))
                .GroupBy(assemblyPath => Path.GetFileName(assemblyPath), StringComparer.OrdinalIgnoreCase)
                .Select(group => group.First());
            MetadataReference[] references = assemblyPaths
                .Select(assemblyPath => MetadataReference.CreateFromFile(assemblyPath))
                .ToArray();

            foreach (string projectName in ProjectNames)
            {
                string directory = Path.Combine(Root, projectName);
                Assert.That(File.Exists(Path.Combine(directory, $"{projectName}.csproj")),
                    $"Required source project {projectName} is unavailable.");
                SyntaxTree[] trees = [.. EnumerateFiles(directory)
                    .OrderBy(filePath => filePath, StringComparer.Ordinal)
                    .Select(filePath => CSharpSyntaxTree.ParseText(
                        File.ReadAllText(filePath), new CSharpParseOptions(LanguageVersion.Preview), filePath))];
                Assert.That(trees, Is.Not.Empty, $"{projectName} has no eligible handwritten sources.");
                compilations.Add(projectName, CSharpCompilation.Create(
                    projectName,
                    trees,
                    references,
                    new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary,
                        nullableContextOptions: NullableContextOptions.Enable)));
            }

            return compilations;
        }
    }
}